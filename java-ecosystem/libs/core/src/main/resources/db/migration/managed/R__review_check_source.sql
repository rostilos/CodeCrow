-- Repair the exact pre-provenance Composer producer format, never all SECURITY
-- findings in a manifest. Retain the records, status decisions and job history.
WITH emitted AS (
    SELECT id, title, regexp_match(reason,
        '^Composer audit: ([a-z0-9_.-]+/[a-z0-9_.-]+) [^[:space:]]+ is affected by (.+?)\. ') AS parts
    FROM code_analysis_issue
    WHERE review_check_id IS NULL AND issue_category = 'SECURITY'
      AND file_path ~ '(^|/)composer\.(json|lock)$'
)
UPDATE code_analysis_issue issue SET review_check_id = 'composer-audit'
FROM emitted
WHERE issue.id = emitted.id AND emitted.title = emitted.parts[1] || ': ' || emitted.parts[2];

-- Reconciliation sometimes retained the canonical title but rewrote the reason.
UPDATE code_analysis_issue copy SET review_check_id = 'composer-audit'
FROM code_analysis_issue original, code_analysis source, code_analysis target
WHERE copy.review_check_id IS NULL AND copy.issue_category = 'SECURITY'
  AND original.review_check_id = 'composer-audit' AND copy.title = original.title
  AND original.title ~ '^[a-z0-9_.-]+/[a-z0-9_.-]+: .+'
  AND copy.file_path ~ '(^|/)composer\.(json|lock)$'
  AND regexp_replace(copy.file_path, 'composer\.(json|lock)$', '')
      = regexp_replace(original.file_path, 'composer\.(json|lock)$', '')
  AND source.id = original.analysis_id AND target.id = copy.analysis_id
  AND source.project_id = target.project_id AND source.pr_number = target.pr_number;

-- Follow trusted lineage only within the same project and PR, including reworded copies.
WITH RECURSIVE owned(id, project_id, pr_number) AS (
    SELECT issue.id, analysis.project_id, analysis.pr_number
    FROM code_analysis_issue issue JOIN code_analysis analysis ON analysis.id = issue.analysis_id
    WHERE issue.review_check_id = 'composer-audit'
    UNION
    SELECT child.id, analysis.project_id, analysis.pr_number
    FROM code_analysis_issue child JOIN code_analysis analysis ON analysis.id = child.analysis_id
    JOIN owned parent ON child.tracked_from_issue_id = parent.id
      AND analysis.project_id = parent.project_id AND analysis.pr_number = parent.pr_number
    WHERE child.review_check_id IS NULL
)
UPDATE code_analysis_issue issue SET review_check_id = 'composer-audit'
FROM owned WHERE issue.id = owned.id AND issue.review_check_id IS NULL;

UPDATE branch_issue issue SET review_check_id = source.review_check_id
FROM code_analysis_issue source, code_analysis analysis, branch
WHERE issue.review_check_id IS NULL AND issue.origin_issue_id = source.id
  AND source.review_check_id = 'composer-audit' AND source.analysis_id = analysis.id
  AND issue.branch_id = branch.id AND branch.project_id = analysis.project_id;

CREATE TABLE IF NOT EXISTS review_check_result (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    analysis_id bigint NOT NULL REFERENCES code_analysis(id) ON DELETE CASCADE,
    check_id varchar(128) NOT NULL,
    complete boolean NOT NULL DEFAULT false,
    diagnostics jsonb NOT NULL DEFAULT '[]',
    UNIQUE (analysis_id, check_id)
);
CREATE TABLE IF NOT EXISTS review_check_finding (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    result_id bigint NOT NULL REFERENCES review_check_result(id) ON DELETE CASCADE,
    finding_key varchar(64) NOT NULL,
    severity varchar(10) NOT NULL,
    file_path varchar(500) NOT NULL,
    line_number integer,
    title varchar(255),
    reason text,
    suggested_fix_description text,
    code_snippet text,
    issue_category varchar(50),
    is_resolved boolean NOT NULL DEFAULT false,
    manual_status_resolved boolean,
    manual_status_updated_at timestamptz,
    resolved_description text,
    UNIQUE (result_id, finding_key)
);
-- Preserve complete legacy records without keeping them in ordinary issue queries.
CREATE TABLE IF NOT EXISTS review_check_legacy_record (
    source_table varchar(30) NOT NULL,
    source_id bigint NOT NULL,
    project_id bigint NOT NULL REFERENCES project(id) ON DELETE CASCADE,
    analysis_id bigint,
    finding_id bigint REFERENCES review_check_finding(id) ON DELETE SET NULL,
    payload jsonb NOT NULL,
    PRIMARY KEY (source_table, source_id)
);

INSERT INTO review_check_result(analysis_id, check_id, complete, diagnostics)
SELECT DISTINCT analysis_id, review_check_id, false,
    '["migrated: prior audit coverage was not recorded; findings are retained as last-known evidence"]'::jsonb
FROM code_analysis_issue WHERE review_check_id IS NOT NULL
ON CONFLICT (analysis_id, check_id) DO NOTHING;

-- A canonical advisory identity wins over old source-tracking links. Only a
-- reworded Composer copy needs its same-project/PR ancestor to recover that key.
CREATE TEMP TABLE migrated_check_issue ON COMMIT DROP AS
WITH RECURSIVE lineage(id, ancestor_id, depth, visited) AS (
    SELECT id, id, 0, ARRAY[id] FROM code_analysis_issue WHERE review_check_id IS NOT NULL
    UNION ALL
    SELECT chain.id, parent.id, chain.depth + 1, chain.visited || parent.id
    FROM lineage chain
    JOIN code_analysis_issue child ON child.id = chain.ancestor_id
    JOIN code_analysis_issue parent ON parent.id = child.tracked_from_issue_id
    JOIN code_analysis ca ON ca.id = child.analysis_id
    JOIN code_analysis pa ON pa.id = parent.analysis_id
    WHERE child.review_check_id = 'composer-audit'
      AND parent.review_check_id = child.review_check_id
      AND ca.project_id = pa.project_id AND ca.pr_number = pa.pr_number
      AND NOT parent.id = ANY(chain.visited)
      AND child.title !~ '^[a-z0-9_.-]+/[a-z0-9_.-]+: .+'
), identities AS (
    SELECT DISTINCT ON (chain.id) chain.id, ancestor.id AS canonical_id,
        ancestor.title AS canonical_title, ancestor.file_path AS canonical_file
    FROM lineage chain JOIN code_analysis_issue ancestor ON ancestor.id = chain.ancestor_id
    ORDER BY chain.id, (ancestor.title ~ '^[a-z0-9_.-]+/[a-z0-9_.-]+: .+') DESC, chain.depth
)
SELECT issue.id, identities.canonical_id, result.id AS result_id, analysis.project_id,
    encode(sha256(convert_to(CASE WHEN issue.review_check_id = 'composer-audit'
        THEN regexp_replace(identities.canonical_file, 'composer\.(json|lock)$', '')
        ELSE identities.canonical_file END, 'UTF8') || decode('00', 'hex')
        || convert_to(COALESCE(identities.canonical_title, ''), 'UTF8')), 'hex') AS finding_key
FROM code_analysis_issue issue
JOIN code_analysis analysis ON analysis.id = issue.analysis_id
JOIN identities ON identities.id = issue.id
JOIN review_check_result result ON result.analysis_id = issue.analysis_id AND result.check_id = issue.review_check_id;

INSERT INTO review_check_finding(result_id, finding_key, severity, file_path, line_number,
    title, reason, suggested_fix_description, code_snippet, issue_category, is_resolved,
    manual_status_resolved, manual_status_updated_at, resolved_description)
SELECT DISTINCT ON (m.result_id, m.finding_key) m.result_id, m.finding_key, original.severity,
    issue.file_path, issue.line_number, original.title, original.reason,
    original.suggested_fix_description, issue.code_snippet, issue.issue_category, issue.is_resolved,
    COALESCE(issue.manual_status_resolved, CASE WHEN issue.resolved_by = 'manual' THEN issue.is_resolved END),
    issue.manual_status_updated_at, issue.resolved_description
FROM migrated_check_issue m JOIN code_analysis_issue issue ON issue.id = m.id
JOIN code_analysis_issue original ON original.id = m.canonical_id
ORDER BY m.result_id, m.finding_key, issue.manual_status_updated_at DESC NULLS LAST, issue.id DESC
ON CONFLICT (result_id, finding_key) DO NOTHING;

INSERT INTO review_check_legacy_record(source_table, source_id, project_id, analysis_id, finding_id, payload)
SELECT 'code_analysis_issue', issue.id, m.project_id, issue.analysis_id, finding.id, to_jsonb(issue)
FROM migrated_check_issue m JOIN code_analysis_issue issue ON issue.id = m.id
JOIN review_check_finding finding ON finding.result_id = m.result_id AND finding.finding_key = m.finding_key
ON CONFLICT (source_table, source_id) DO NOTHING;

CREATE TEMP TABLE migrated_check_branch_issue ON COMMIT DROP AS
SELECT issue.id, issue.branch_id FROM branch_issue issue WHERE issue.review_check_id IS NOT NULL;
INSERT INTO review_check_legacy_record(source_table, source_id, project_id, analysis_id, finding_id, payload)
SELECT 'branch_issue', issue.id, branch.project_id, issue.origin_analysis_id, finding.id, to_jsonb(issue)
FROM migrated_check_branch_issue moved JOIN branch_issue issue ON issue.id = moved.id
JOIN branch ON branch.id = issue.branch_id
LEFT JOIN migrated_check_issue m ON m.id = issue.origin_issue_id AND m.project_id = branch.project_id
LEFT JOIN review_check_finding finding ON finding.result_id = m.result_id AND finding.finding_key = m.finding_key
ON CONFLICT (source_table, source_id) DO NOTHING;

DELETE FROM branch_issue WHERE id IN (SELECT id FROM migrated_check_branch_issue);
-- Non-check references remain ordinary records; detach their former provenance.
UPDATE branch_issue SET origin_issue_id = NULL WHERE origin_issue_id IN (SELECT id FROM migrated_check_issue);
UPDATE code_analysis_issue SET tracked_from_issue_id = NULL WHERE tracked_from_issue_id IN (SELECT id FROM migrated_check_issue);
DELETE FROM code_analysis_issue WHERE id IN (SELECT id FROM migrated_check_issue);

UPDATE code_analysis analysis SET
    total_issues = counts.open, high_severity_count = counts.high, medium_severity_count = counts.medium,
    low_severity_count = counts.low, info_severity_count = counts.info, resolved_count = counts.resolved
FROM (
    SELECT a.id, count(i.id) FILTER (WHERE NOT i.is_resolved) AS open,
        count(i.id) FILTER (WHERE NOT i.is_resolved AND i.severity = 'HIGH') AS high,
        count(i.id) FILTER (WHERE NOT i.is_resolved AND i.severity = 'MEDIUM') AS medium,
        count(i.id) FILTER (WHERE NOT i.is_resolved AND i.severity = 'LOW') AS low,
        count(i.id) FILTER (WHERE NOT i.is_resolved AND i.severity = 'INFO') AS info,
        count(i.id) FILTER (WHERE i.is_resolved) AS resolved
    FROM code_analysis a LEFT JOIN code_analysis_issue i ON i.analysis_id = a.id
    WHERE a.id IN (SELECT result.analysis_id FROM review_check_result result JOIN migrated_check_issue m ON m.result_id = result.id)
    GROUP BY a.id
) counts WHERE analysis.id = counts.id;
UPDATE branch SET
    total_issues = counts.open, high_severity_count = counts.high, medium_severity_count = counts.medium,
    low_severity_count = counts.low, info_severity_count = counts.info, resolved_count = counts.resolved
FROM (
    SELECT b.id, count(i.id) FILTER (WHERE NOT i.is_resolved) AS open,
        count(i.id) FILTER (WHERE NOT i.is_resolved AND i.severity = 'HIGH') AS high,
        count(i.id) FILTER (WHERE NOT i.is_resolved AND i.severity = 'MEDIUM') AS medium,
        count(i.id) FILTER (WHERE NOT i.is_resolved AND i.severity = 'LOW') AS low,
        count(i.id) FILTER (WHERE NOT i.is_resolved AND i.severity = 'INFO') AS info,
        count(i.id) FILTER (WHERE i.is_resolved) AS resolved
    FROM branch b LEFT JOIN branch_issue i ON i.branch_id = b.id
    WHERE b.id IN (SELECT branch_id FROM migrated_check_branch_issue) GROUP BY b.id
) counts WHERE branch.id = counts.id;

