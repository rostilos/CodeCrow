-- Feedback is audit data; source issue/user identifiers remain as provenance
-- after normal review-history cleanup. Project deletion removes its learning.
CREATE TABLE review_learned_rule (
    id varchar(36) PRIMARY KEY,
    workspace_id bigint NOT NULL REFERENCES workspace(id) ON DELETE CASCADE,
    project_id bigint NOT NULL REFERENCES project(id) ON DELETE CASCADE,
    pattern_key varchar(64) NOT NULL,
    title varchar(200) NOT NULL,
    file_path varchar(500) NOT NULL,
    issue_category varchar(50),
    description text NOT NULL,
    rule_type varchar(20) NOT NULL,
    state varchar(20) NOT NULL,
    promoted_by bigint,
    promoted_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (workspace_id, project_id, pattern_key)
);
CREATE TABLE review_finding_feedback (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule_id varchar(36) NOT NULL REFERENCES review_learned_rule(id) ON DELETE CASCADE,
    workspace_id bigint NOT NULL REFERENCES workspace(id) ON DELETE CASCADE,
    project_id bigint NOT NULL REFERENCES project(id) ON DELETE CASCADE,
    issue_id bigint NOT NULL,
    analysis_id bigint NOT NULL,
    commit_hash varchar(64),
    user_id bigint NOT NULL,
    verdict varchar(20) NOT NULL,
    explanation text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_review_feedback_current
    ON review_finding_feedback(workspace_id, project_id, rule_id, issue_id, user_id, id DESC);
CREATE INDEX idx_review_learned_rule_project
    ON review_learned_rule(workspace_id, project_id, updated_at DESC);
